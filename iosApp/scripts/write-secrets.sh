#!/bin/sh
# Writes iosApp/Configuration/Secrets.xcconfig (gitignored, mode 600) from the
# environment, so the key never appears on a command line. Run it through the
# key store, which injects the variable into this process only:
#
#   tools/keys/glosso-secret run GLOSSO_API_KEY -- iosApp/scripts/write-secrets.sh
#
# Optional: GLOSSO_API_BASE to point the app at another server.
set -eu

out="$(cd "$(dirname "$0")/.." && pwd)/Configuration/Secrets.xcconfig"
umask 077
{
    echo "// Generated by iosApp/scripts/write-secrets.sh. Never commit this file."
    if [ -n "${GLOSSO_API_KEY:-}" ]; then
        echo "GLOSSO_API_KEY = ${GLOSSO_API_KEY}"
    fi
    if [ -n "${GLOSSO_API_BASE:-}" ]; then
        # xcconfig reads "//" as a comment; $() breaks it without changing the value.
        echo "GLOSSO_API_BASE = $(printf '%s' "$GLOSSO_API_BASE" | sed 's#//#/$()/#')"
    fi
} > "$out"
chmod 600 "$out"
echo "Wrote $out"
