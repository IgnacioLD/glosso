package com.glosso.engine.phonetics.cheap

import kotlin.math.abs
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue
import kotlin.test.fail
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.doubleOrNull
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive

/**
 * Pins the Kotlin port of the cheap scorers to the Python reference in
 * `benchmark/cheap-scorers` (PR #43, branch `research/cheap-scorers`).
 *
 * The fixtures under `resources/cheap/` were generated by `gen_fixtures.py` from
 * that reference: deterministic WAVs plus the exact features and accent score the
 * Python produced on the very same bytes. If the port drifts, the report's
 * numbers stop holding in production, so this test fails.
 *
 * Tolerances are explicit and per feature: the DSP is reimplemented from first
 * principles (own radix-2 FFT, own percentile, own scipy-compatible peak finder),
 * so tiny floating-point differences are expected and are not allowed to hide a
 * real regression.
 */
class CheapParityTest {

    private val golden: JsonObject by lazy {
        val text = readResource("cheap/golden.json").decodeToString()
        Json.parseToJsonElement(text).jsonObject
    }

    private val tolerances: Map<String, Double> = mapOf(
        // Formants and spectral moments (Hz): below one FFT bin (15.6 Hz) at nfft=1024.
        "f1" to 1.5, "f2" to 1.5, "f3" to 1.5, "f2_minus_f1" to 3.0,
        "f1_std" to 1.0, "f2_std" to 1.0,
        "fric_centroid" to 1.0, "fric_spread" to 1.0,
        // Dimensionless moments and ratios.
        "fric_skew" to 1e-9, "fric_kurtosis" to 1e-9, "fric_flatness" to 1e-11,
        "fric_high_ratio" to 1e-11, "fric_zcr" to 1e-11, "voiced_ratio" to 1e-11,
        "pause_ratio" to 1e-11,
        // Times and rates.
        "fric_duration" to 1e-11, "speech_seconds" to 1e-11, "nucleus_seconds" to 1e-11,
        "onset_seconds" to 1e-11, "coda_seconds" to 1e-11,
        "mean_nucleus_seconds" to 1e-11, "std_nucleus_seconds" to 1e-11,
        "longest_pause_seconds" to 1e-11, "mean_pause_seconds" to 1e-11,
        "speech_rate_syl_per_s" to 1e-9, "articulation_rate_syl_per_s" to 1e-9,
        "npvi" to 1e-9,
        // Pitch.
        "f0_mean" to 0.05, "f0_median" to 0.05, "f0_std_semitones" to 1e-6,
        "f0_range_semitones" to 1e-6, "f0_slope_semitones_per_s" to 1e-6,
        "f0_final_delta_semitones" to 1e-6,
        // Counts are exact.
        "n_syllables" to 0.0, "pause_count" to 0.0,
    )

    private fun tolerance(key: String): Double = tolerances[key] ?: 1e-6

    @Test
    fun `features match the python reference on the same signals`() {
        val signals = golden.getValue("signals").jsonArray
        assertTrue(signals.isNotEmpty(), "golden must carry signals")
        val failures = ArrayList<String>()
        var compared = 0

        for (signal in signals) {
            val obj = signal.jsonObject
            val id = obj.getValue("id").jsonPrimitive.content
            val pcm = readPcm("cheap/${obj.getValue("file").jsonPrimitive.content}")
            val sampleRate = obj.getValue("sampleRate").jsonPrimitive.content.toInt()
            val focus = obj["focus"]?.takeIf { it !is JsonNull }?.jsonPrimitive?.content
            val actual = CheapFeatures.extract(pcm, sampleRate, focus)
            val expectedFeatures = obj.getValue("features").jsonObject

            for ((key, expectedElement) in expectedFeatures) {
                if (key == "focus_class") {
                    compared++
                    val expectedClass = if (expectedElement is JsonNull) null else expectedElement.jsonPrimitive.content
                    if (expectedClass != actual.focusClass) {
                        failures.add("$id/$key: expected=$expectedClass actual=${actual.focusClass}")
                    }
                    continue
                }
                val expected = expectedElement.doubleOrNullValue()
                val got = actualValue(actual, key)
                compared++
                if (expected == null || got == null) {
                    if (expected != null || got != null) {
                        failures.add("$id/$key: expected=$expected actual=$got")
                    }
                    continue
                }
                val diff = abs(expected - got)
                if (diff > tolerance(key)) {
                    failures.add("$id/$key: expected=$expected actual=$got diff=$diff > tol=${tolerance(key)}")
                }
            }
        }

        assertTrue(compared > 50, "the golden should compare many features, got $compared")
        if (failures.isNotEmpty()) {
            fail("parity failures (${failures.size}):\n" + failures.joinToString("\n"))
        }
    }

    @Test
    fun `accent score matches the python reference on the same signals`() {
        val signals = golden.getValue("signals").jsonArray
        for (signal in signals) {
            val obj = signal.jsonObject
            val id = obj.getValue("id").jsonPrimitive.content
            val pcm = readPcm("cheap/${obj.getValue("file").jsonPrimitive.content}")
            val sampleRate = obj.getValue("sampleRate").jsonPrimitive.content.toInt()
            val features = CheapFeatures.extract(pcm, sampleRate, null)
            val expected = obj.getValue("accentScore").doubleOrNullValue() ?: continue
            val got = FluencyScorer.accentScore(features) ?: fail("$id: no accent score")
            val diff = abs(expected - got)
            assertTrue(diff <= 1e-6, "$id: accent expected=$expected actual=$got diff=$diff")
        }
    }

    /**
     * The fixed production anchors must be the ones the parity fixtures were
     * generated with, or the report's AUC 0.777 no longer describes production.
     */
    @Test
    fun `production fluency anchors match the golden norm`() {
        val norm = golden.getValue("norm").jsonObject
        assertEquals(norm.keys, FluencyScorer.ENGLISH.keys, "anchor feature sets differ")
        for ((key, entry) in norm) {
            val production = FluencyScorer.ENGLISH.getValue(key)
            val mean = entry.jsonObject.getValue("mean").jsonPrimitive.doubleOrNull!!
            val std = entry.jsonObject.getValue("std").jsonPrimitive.doubleOrNull!!
            val sign = entry.jsonObject.getValue("sign").jsonPrimitive.content.toInt()
            assertEquals(mean, production.mean, "anchors[$key].mean")
            assertEquals(std, production.std, "anchors[$key].std")
            assertEquals(sign, production.sign, "anchors[$key].sign")
        }
    }

    private fun actualValue(f: CheapFeatures.Result, key: String): Double? = when (key) {
        "f1" -> f.f1; "f2" -> f.f2; "f3" -> f.f3; "f2_minus_f1" -> f.f2MinusF1
        "f1_std" -> f.f1Std; "f2_std" -> f.f2Std
        "fric_centroid" -> f.fricCentroid; "fric_spread" -> f.fricSpread; "fric_skew" -> f.fricSkew
        "fric_kurtosis" -> f.fricKurtosis; "fric_flatness" -> f.fricFlatness
        "fric_high_ratio" -> f.fricHighRatio; "fric_zcr" -> f.fricZcr; "fric_duration" -> f.fricDuration
        "f0_mean" -> f.f0Mean; "f0_median" -> f.f0Median; "f0_std_semitones" -> f.f0StdSemitones
        "f0_range_semitones" -> f.f0RangeSemitones; "f0_slope_semitones_per_s" -> f.f0SlopeSemitonesPerS
        "f0_final_delta_semitones" -> f.f0FinalDeltaSemitones; "voiced_ratio" -> f.voicedRatio
        "speech_seconds" -> f.speechSeconds; "n_syllables" -> f.nSyllables.toDouble()
        "speech_rate_syl_per_s" -> f.speechRateSylPerS; "articulation_rate_syl_per_s" -> f.articulationRateSylPerS
        "mean_nucleus_seconds" -> f.meanNucleusSeconds; "std_nucleus_seconds" -> f.stdNucleusSeconds
        "npvi" -> f.npvi; "pause_count" -> f.pauseCount.toDouble()
        "pause_ratio" -> f.pauseRatio; "longest_pause_seconds" -> f.longestPauseSeconds
        "mean_pause_seconds" -> f.meanPauseSeconds
        "nucleus_seconds" -> f.nucleusSeconds; "onset_seconds" -> f.onsetSeconds; "coda_seconds" -> f.codaSeconds
        else -> null
    }

    private fun kotlinx.serialization.json.JsonElement?.doubleOrNullValue(): Double? =
        if (this == null || this is JsonNull) null else jsonPrimitive.doubleOrNull

    private fun readResource(path: String): ByteArray =
        CheapParityTest::class.java.getResourceAsStream("/$path")?.readAllBytes()
            ?: fail("missing test resource: $path")

    /** Canonical 44-byte-header WAV, int16 mono, scaled exactly like the reference. */
    private fun readPcm(path: String): DoubleArray {
        val bytes = readResource(path)
        val dataStart = 44
        val sampleCount = (bytes.size - dataStart) / 2
        return DoubleArray(sampleCount) { i ->
            val b0 = bytes[dataStart + i * 2].toInt() and 0xff
            val b1 = bytes[dataStart + i * 2 + 1].toInt() and 0xff
            ((b0 or (b1 shl 8)).toShort()).toDouble() / 32768.0
        }
    }
}
