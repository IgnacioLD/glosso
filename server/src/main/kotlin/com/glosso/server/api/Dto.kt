/**
 * Drill plan request. The learner sends the phonetic profile the scorer returned;
 * the server plans from the reviewed bank, never generating content itself.
 *
 * [themes] is the selection the learner made on the post-placement screen (empty
 * means "any"). [targets] narrows the plan to specific sounds, e.g. the
 * drillTargets of the lesson being played (empty means "any"). [seenIds] are
 * drills already shown, so practice does not repeat.
 */
@Serializable
data class DrillRequest(
    val profile: PhoneticProfileModel,
    val limit: Int = 3,
    val themes: List<String> = emptyList(),
    val targets: List<String> = emptyList(),
    val level: String? = null,
    val seenIds: List<String> = emptyList(),
    val language: String = "en",
)

/** Audio in, model IPA out: the content pipeline turns TTS audio into an IPA. */
@Serializable
data class PhonemizeRequest(
    val audioBase64: String,
)

@Serializable
data class PhonemizeResponse(
    val ipa: String,
)

/**
 * Force-aligns known text against TTS audio. This is the content pipeline's
 * reference: the intended CMUdict pronunciation placed on the audio, plus a score
 * that tells whether the TTS was actually intelligible. The model's own greedy
 * decode ([transcription]) is returned only as a sanity check, never as the
 * reference, because it drops or merges sounds at the end of an utterance.
 */
@Serializable
data class AlignRequest(
    val text: String,
    val audioBase64: String,
    val language: String = "en",
)

@Serializable
data class AlignResponse(
    /** The reference IPA (CMUdict, with stress) used for scoring. */
    val expected: String,
    /** What the model actually heard (greedy decode), for diagnostics. */
    val transcription: String,
    /** How well the audio matches the reference, 0..100. Low means bad TTS. */
    val score: Int,
    val accuracy: Int,
    val timings: List<com.glosso.engine.model.PhoneTimingModel> = emptyList(),
)

/**
 * A learner-requested theme, from the "is something missing?" note on the drill
 * picker. Stored as a first-party event so the content team can see the most
 * requested themes and fold them into a weekly release. Anonymous: [deviceId] is
 * the same per-install id used elsewhere, never a hardware identifier.
 */
@Serializable
data class ThemeSuggestionRequest(
    val theme: String,
    val note: String? = null,
    val deviceId: String? = null,
    val language: String = "en",
    val level: String? = null,
    val weakSounds: List<String> = emptyList(),
)

@Serializable
data class ThemeSuggestionResponse(
    val accepted: Boolean,
)

/**
 * One sound's aggregate in a profile sync. It carries only numbers the on-device
 * scorer already produced: never audio, never the reference text, never a note.
 * [lastSeen] is an ISO-8601 instant; the server stores it, not the client.
 */
@Serializable
data class PhonemeSnapshotDto(
    val phoneme: String,
    val score: Int = 0,
    val confidence: Float = 0f,
    val errorPattern: String? = null,
    val replacementPhoneme: String? = null,
    val position: String? = null,
    val attempts: Int = 0,
    val successfulAttempts: Int = 0,
    val lastSeen: String? = null,
    val trend: String? = null,
)

/**
 * The ingest seam of the generation engine: the learner's aggregate profile,
 * keyed by an anonymous per-install [deviceId]. The payload is aggregate by
 * design ("A1 / θ / substitution-t / initial"), not an identifiable history.
 *
 * Audio and personal data are rejected outright by the route before decoding;
 * see docs/NEED-ENGINE.md for the contract.
 */
@Serializable
data class ProfileSyncRequest(
    val deviceId: String,
    val language: String = "en",
    val cefr: String? = null,
    val vocabularyScore: Int? = null,
    val grammarScore: Int? = null,
    val comprehensionScore: Int? = null,
    val pronunciationScore: Int? = null,
    val fluencyScore: Int? = null,
    val speakingScore: Int? = null,
    val sampleCounts: JsonObject = JsonObject(emptyMap()),
    val phonemes: List<PhonemeSnapshotDto> = emptyList(),
)

