/**
 * Scoring request.
 *
 * Supply either [audioBase64] (the real path: the server recognizes the audio and
 * scores it) or [actualIpa] (an already-recognized transcription, used by tests and
 * by clients that recognized on-device). At least one is required.
 *
 * [expectedIpa] is optional: when omitted, the server phonemizes [text] with its
 * CMUdict asset. Provide it when the reference uses a different phonemization.
 *
 * [profile] is the learner's phonetic profile from previous attempts. When sent,
 * this attempt is folded into it and the updated profile comes back in the
 * response; the server stores nothing itself.
 */
@Serializable
data class ScoreRequest(
    val text: String,
    val expectedIpa: String? = null,
    val actualIpa: String? = null,
    val audioBase64: String? = null,
    val language: String = "en_GB",
    val uiLanguage: String = "en",
    val profile: PhoneticProfileModel? = null,
    /**
     * The accent the learner is mastering ("en-US-South"). With multi-accent
     * scoring on it only breaks exact ties between systems; it never lowers a
     * take that matches another accent better.
     */
    val accent: String? = null,
    /**
     * Whole-sentence references already in one accent, keyed by system id
     * ("en-IE-male") or accent ("en-IE"), e.g. phonemized from that voice's clip.
     * Scored next to each system's rule-derived reading; only read when
     * multi-accent scoring is on. [expectedIpa] stays the canonical (CMUdict)
     * reading that every system realizes in its own accent.
     */
    val accentIpa: Map<String, String> = emptyMap(),
)

/**
 * One client-side analytics event. [deviceId] must be an anonymous, per-install
 * identifier generated by the app; hardware identifiers and the advertising ID
 * are never accepted. Only the events and properties of
 * [com.glosso.server.analytics.ClientEvents] are stored; the rest is dropped.
 */
@Serializable
data class AnalyticsEventDto(
    val name: String,
    val deviceId: String? = null,
    val sessionId: String? = null,
    val appVersion: String? = null,
    val platform: String? = null,
    val language: String? = null,
    val properties: JsonObject = JsonObject(emptyMap()),
    /** Epoch millis on the device, so a queued event keeps its time. */
    val occurredAt: Long? = null,
)

@Serializable
data class AnalyticsIngestRequest(
    val events: List<AnalyticsEventDto> = emptyList(),
    /**
     * The device clock when the batch was sent. With it each event is dated by
     * how long ago it happened on the device, so a wrong device clock cancels out.
     */
    val sentAt: Long? = null,
)

@Serializable
data class AnalyticsIngestResponse(
    val accepted: Int,
    /** Events that are not in the client catalogue and were not stored. */
    val dropped: Int = 0,
)

@Serializable
data class AnalyticsDeleteResponse(
    val deleted: Int,
)

